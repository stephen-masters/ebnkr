#!/usr/bin/env node
/**
 * build-registry.mjs — generate src/registry.ts from the SWIFT IBAN Registry.
 *
 * Purpose
 *   The validator checks each IBAN against its country's entry in the SWIFT
 *   IBAN Registry: the total length and the structure of the BBAN (the
 *   national account number). This script turns that registry into a typed,
 *   frozen TypeScript module, so that nothing is fetched or parsed at runtime.
 *
 * Source
 *   swift.com refuses automated downloads, so the registry is read from the
 *   machine-readable copy that the schwifty project (MIT licence) parses from
 *   SWIFT's "IBAN Registry (TXT)" release: schwifty/iban_registry/generated.json
 *   at a pinned tag. The file's SHA-256 is pinned too, so a changed upstream
 *   file fails the build instead of silently changing what is valid.
 *
 *   Only official entries are used. Territories that SWIFT lists under their
 *   own country code but whose IBANs carry the parent's prefix (AX uses FI,
 *   JE uses GB, and so on) are skipped: an IBAN starting "AX" is not valid.
 *
 * Prerequisites
 *   Node 22 or later (for the global fetch). No dependencies.
 *
 * Usage
 *   node scripts/build-registry.mjs                  # fetch the pinned file
 *   node scripts/build-registry.mjs --file gen.json  # use a local copy
 *
 *   Then run `npm run lint:fix && npm test`. To move to a new registry
 *   release, update SCHWIFTY_TAG and SCHWIFTY_SHA256 below, run the script,
 *   and review the diff of src/registry.ts: a changed country is a change in
 *   what the library accepts, so it is a `feat:` commit, never a `fix:`.
 */

import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const SCHWIFTY_TAG = '2026.10.1';
const SCHWIFTY_SHA256 = '84b9555e5b3e3c2b3009fafa85193dcb7de9b9766d8d434553a654adffa15895';
const SOURCE_URL = `https://raw.githubusercontent.com/mdomke/schwifty/${SCHWIFTY_TAG}/schwifty/iban_registry/generated.json`;
const OUTPUT = fileURLToPath(new URL('../src/registry.ts', import.meta.url));

/** SWIFT's notation: n = digits, a = upper-case letters, c = alphanumerics. */
const CHARACTER_CLASSES = { n: '[0-9]', a: '[A-Z]', c: '[A-Z0-9]' };
const TOKEN = /(\d+)(!?)([nac])/g;

async function loadSource(args) {
  const fileIndex = args.indexOf('--file');
  if (fileIndex !== -1) {
    const path = args[fileIndex + 1];
    if (!path) throw new Error('--file needs a path');
    return { bytes: await readFile(path), origin: path };
  }
  const response = await fetch(SOURCE_URL);
  if (!response.ok) throw new Error(`${SOURCE_URL}: HTTP ${response.status}`);
  return { bytes: Buffer.from(await response.arrayBuffer()), origin: SOURCE_URL };
}

/** Turns a SWIFT structure such as "4!a6!n8!n" into a regular expression body. */
function toPattern(spec, country) {
  let consumed = '';
  let length = 0;
  const parts = [];
  for (const [token, count, fixed, kind] of spec.matchAll(TOKEN)) {
    const n = Number(count);
    if (fixed !== '!') throw new Error(`${country}: variable-length field ${token} is not supported`);
    parts.push(`${CHARACTER_CLASSES[kind]}{${n}}`);
    consumed += token;
    length += n;
  }
  if (consumed !== spec) throw new Error(`${country}: cannot parse structure "${spec}"`);
  return { pattern: parts.join(''), length };
}

function buildEntries(registry) {
  const entries = [];
  const skipped = [];
  for (const [country, entry] of Object.entries(registry).sort(([a], [b]) => a.localeCompare(b))) {
    if (!/^[A-Z]{2}$/.test(country)) throw new Error(`Unexpected country key "${country}"`);
    const prefix = `${country}2!n`;
    if (!entry.iban_spec.startsWith(prefix)) {
      skipped.push(`${country} (uses ${entry.iban_spec.slice(0, 2)})`);
      continue;
    }
    const bbanSpec = entry.iban_spec.slice(prefix.length);
    const { pattern, length } = toPattern(bbanSpec, country);
    if (length !== entry.bban_length || length + 4 !== entry.iban_length) {
      throw new Error(`${country}: structure ${bbanSpec} does not add up to ${entry.iban_length} characters`);
    }
    entries.push({ country, length: entry.iban_length, bbanSpec, pattern, sepa: entry.in_sepa_zone === true });
  }
  return { entries, skipped };
}

function render(entries, origin, sha256) {
  const lines = entries.map(e =>
    `  ${e.country}: { length: ${e.length}, bbanStructure: '${e.bbanSpec}', bban: /^${e.pattern}$/, sepa: ${e.sepa} }`
  );
  return `// Generated by scripts/build-registry.mjs. Do not edit by hand.
//
// Source: the SWIFT IBAN Registry, as parsed by schwifty ${SCHWIFTY_TAG} (MIT licence)
// ${origin}
// SHA-256 ${sha256}

/** One country's entry in the SWIFT IBAN Registry. */
export interface CountrySpec {
  /** The total length of an IBAN for this country, in its electronic format. */
  readonly length: number;
  /** The BBAN structure in SWIFT's notation, for example \`4!a6!n8!n\`. */
  readonly bbanStructure: string;
  /** Matches a BBAN, in upper case, that follows that structure. */
  readonly bban: RegExp;
  /** Whether the country is in the Single Euro Payments Area. */
  readonly sepa: boolean;
}

/** Every country in the SWIFT IBAN Registry, keyed by ISO 3166-1 alpha-2 code. */
export const registry: Readonly<Record<string, CountrySpec>> = Object.freeze({
${lines.join(',\n')}
});
`;
}

const { bytes, origin } = await loadSource(process.argv.slice(2));
const sha256 = createHash('sha256').update(bytes).digest('hex');
if (sha256 !== SCHWIFTY_SHA256) {
  throw new Error(`SHA-256 mismatch for ${origin}: expected ${SCHWIFTY_SHA256}, got ${sha256}`);
}
const { entries, skipped } = buildEntries(JSON.parse(bytes.toString('utf8')));
await writeFile(OUTPUT, render(entries, SOURCE_URL, sha256));
console.log(`Wrote ${entries.length} countries to src/registry.ts`);
console.log(`Skipped territories that use another country's prefix: ${skipped.join(', ')}`);
